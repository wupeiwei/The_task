void oled_show_char(uint8_t page, uint8_t col, char ch)
{
    if (ch < 0x20 || ch > 0x7F) ch = ' ';   /* 只支持可打印 ASCII */
    oled_set_pos(page, col);
    oled_write_data(font6x8[ch - 0x20], 5);
}

void oled_show_string(uint8_t page, uint8_t col, const char *str)
{
    while (*str)
    {
        oled_show_char(page, col, *str++);
        col += 6;                 /* 5 列字符 + 1 列间距 */
        if (col > 127) break;     /* 防越界 */
    }
}

/* 右对齐定宽数字显示（len 为占位宽度，不足补空格） */
void oled_show_num(uint8_t page, uint8_t col, int32_t num, uint8_t len)
{
    char buf[12];
    uint8_t i = 11;
    buf[i--] = '\0';
    uint32_t n;
    if (num < 0)
    {
        buf[i--] = '-';                 /* 负号先占位 */
        n = (uint32_t)(-(int64_t)num);  /* int64 中间量防 INT32_MIN 取负溢出 */
    }
    else
        n = (uint32_t)num;
    do { buf[i--] = '0' + (n % 10); n /= 10; } while (n > 0);  /* 无符号转换，不依赖负数取余 */
    while (i > 0 && strlen(&buf[i + 1]) < len) buf[i--] = ' '; /* 不足 len 前补空格（右对齐） */
    oled_show_string(page, col, &buf[i + 1]);
}
